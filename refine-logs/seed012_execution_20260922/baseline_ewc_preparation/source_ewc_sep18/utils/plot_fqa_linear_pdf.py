# ── constants ─────────────────────────────────────────────────────────────────

SETTINGS = ("sgd", "gam_beta111")
SETTING_LABELS = {"sgd": "SGD", "gam_beta111": r"GAM ($\beta$=111)"}
SETTING_COLORS = {"sgd": "#1f77b4", "gam_beta111": "#ff7f0e"}
SETTING_MARKERS = {"sgd": "o", "gam_beta111": "s"}

# (csv_column, y-axis label, panel title)
PANELS: List[Tuple[str, str, str]] = [
    (
        "loss_delta_abs",
        r"$\mathbb{E}_u|\Delta L_A(r,u)|$",
        r"(a) True old-task loss movement",
    ),
    (
        "endpoint_fisher_quad",
        r"$\mathbb{E}_u[Q_F(r,u)]$",
        r"(b) Fisher quadratic surrogate",
    ),
    (
        "endpoint_error",
        r"$\mathbb{E}_u|\Delta L_A - Q_F|$",
        r"(c) Raw surrogate error",
    ),
    (
        "linear_term_abs",
        r"$\mathbb{E}_u|g_A^\top(ru)|$",
        r"(d) First-order stationarity term",
    ),
]


# ── helpers ───────────────────────────────────────────────────────────────────

def _float(v: object) -> float:
    try:
        return float(str(v).strip())
    except Exception:
        return float("nan")


def read_rows(result_dir: Path) -> List[Dict[str, str]]:
    with (result_dir / "fqa_partial_means.csv").open(newline="", encoding="utf-8") as f:
        rows = list(csv.DictReader(f))
    return [r for r in rows if r.get("main_prefix") == "endpoint"]


def read_rows_merged(result_dir: Path) -> List[Dict[str, str]]:
    """Return one merged row per (setting, radius) combining endpoint columns
    and mf_ncm_empirical columns.  Endpoint fields take precedence; mf fields
    fill in the gaps."""
    with (result_dir / "fqa_partial_means.csv").open(newline="", encoding="utf-8") as f:
        all_rows = list(csv.DictReader(f))

    ep_idx: Dict[tuple, Dict[str, str]] = {}
    mf_idx: Dict[tuple, Dict[str, str]] = {}
    for row in all_rows:
        key = (row["setting"], row["radius"])
        if row.get("main_prefix") == "endpoint":
            ep_idx[key] = row
        elif row.get("main_prefix") == "mf_ncm_empirical":
            mf_idx[key] = row

    merged: List[Dict[str, str]] = []
    for key, ep_row in ep_idx.items():
        merged_row = dict(ep_row)
        for k, v in mf_idx.get(key, {}).items():
            if v and not merged_row.get(k):
                merged_row[k] = v
        merged.append(merged_row)
    return merged


def points_for(
    rows: List[Dict[str, str]],
    setting: str,
    metric: str,
    r_max: Optional[float] = None,
) -> List[Tuple[float, float]]:
    pts = []
    for row in rows:
        if row.get("setting") != setting:
            continue
        r = _float(row.get("radius", "nan"))
        y = _float(row.get(metric, "nan"))
        if r > 0 and math.isfinite(r) and math.isfinite(y):
            if r_max is None or r <= r_max + 1e-9:
                pts.append((r, y))
    return sorted(pts)


def fit_power(pts: List[Tuple[float, float]]) -> Dict[str, float]:
    """Free power-law OLS: log y = log c + p * log r."""
    xs = [math.log(r) for r, y in pts if r > 0 and y > 0]
    ys = [math.log(y) for r, y in pts if r > 0 and y > 0]
    if len(xs) < 2:
        return {"c": float("nan"), "p": float("nan"), "r2": float("nan")}
    mx, my = sum(xs) / len(xs), sum(ys) / len(ys)
    den = sum((x - mx) ** 2 for x in xs)
    if den == 0:
        return {"c": float("nan"), "p": float("nan"), "r2": float("nan")}
    p = sum((x - mx) * (y - my) for x, y in zip(xs, ys)) / den
    b = my - p * mx
    ss_res = sum((y - (b + p * x)) ** 2 for x, y in zip(xs, ys))
    ss_tot = sum((y - my) ** 2 for y in ys)
    r2 = 1.0 - ss_res / ss_tot if ss_tot > 0 else float("nan")
    return {"c": math.exp(b), "p": p, "r2": r2}


def _fit_curve(
    fit: Dict[str, float], r_min: float, r_max: float, n: int = 200
) -> Tuple[List[float], List[float]]:
    c, p = fit["c"], fit["p"]
    if not (math.isfinite(c) and math.isfinite(p) and c > 0):
        return [], []
    rs = [r_min * ((r_max / r_min) ** (i / (n - 1))) for i in range(n)]
    return rs, [c * r ** p for r in rs]


# ── figure ────────────────────────────────────────────────────────────────────

def draw_2x2_linear_pdf(
    result_dir: Path,
    rows: List[Dict[str, str]],
    x_max: Optional[float] = None,
    out_name: str = "fqa_linear_2x2.pdf",
) -> Path:
    """Draw the 2×2 panel figure.

    Args:
        result_dir: directory for reading data and writing output.
        rows:       parsed fqa_radius_diagnostics.csv rows.
        x_max:      if given, restrict data and fit to r ≤ x_max.
        out_name:   output filename (PDF) relative to result_dir.
    """
    all_r = sorted({_float(row["radius"]) for row in rows if _float(row["radius"]) > 0})
    r_min_global = min(all_r) if all_r else 0.0025

    # Effective x-axis ceiling
    r_ceil = x_max if x_max is not None else (max(all_r) if all_r else 1.0)

    fig, axes = plt.subplots(2, 2, figsize=(10, 7.5))
    fig.suptitle(
        "FQA linear diagnostics: Taylor decomposition of old-task loss movement",
        fontsize=12,
        fontweight="bold",
    )

    for ax, (metric, ylabel, title) in zip(axes.flatten(), PANELS):
        for setting in SETTINGS:
            color   = SETTING_COLORS[setting]
            marker  = SETTING_MARKERS[setting]
            slabel  = SETTING_LABELS[setting]

            pts = points_for(rows, setting, metric, r_max=x_max)
            if not pts:
                continue

            rs_data = [r for r, _ in pts]
            ys_data = [y for _, y in pts]

            # fit uses only the visible (possibly filtered) points
            fit = fit_power(pts)

            if all(math.isfinite(fit[k]) for k in ("c", "p", "r2")):
                leg_label = f"{slabel}  $p$={fit['p']:.3f}, $R^2$={fit['r2']:.3f}"
            else:
                leg_label = slabel

            # scatter — marker in legend carries p / R² annotation
            ax.scatter(
                rs_data, ys_data,
                color=color, marker=marker, s=28,
                zorder=4, linewidths=0.4, edgecolors="white",
                label=leg_label,
            )

            # dashed fit line over [r_min_global, r_ceil]
            r_curve, y_curve = _fit_curve(fit, r_min_global, r_ceil)
            if r_curve:
                ax.plot(
                    r_curve, y_curve,
                    color=color, linestyle="--", linewidth=1.7,
                    zorder=3, alpha=0.82,
                )

        ax.set_xlim(0.0, r_ceil * 1.06)
        ax.set_ylim(bottom=0)
        ax.set_xlabel("radius $r$", fontsize=12)
        ax.set_ylabel(ylabel, fontsize=13)
        ax.set_title(title, fontsize=12, fontweight="bold", pad=5)

        fmt = ScalarFormatter(useMathText=True)
        fmt.set_scientific(True)
        fmt.set_powerlimits((-3, 3))
        ax.yaxis.set_major_formatter(fmt)
        ax.tick_params(axis="y", labelsize=11)
        ax.tick_params(axis="x", labelsize=10)
        ax.yaxis.get_offset_text().set_fontsize(10)

        ax.legend(
            loc="upper left",
            fontsize=9,
            framealpha=0.88,
            handletextpad=0.4,
            borderpad=0.5,
            labelspacing=0.35,
        )
        ax.grid(True, alpha=0.22, linewidth=0.5)
        ax.spines["top"].set_visible(False)
        ax.spines["right"].set_visible(False)

    plt.tight_layout()
    out = result_dir / out_name
    fig.savefig(str(out), format="pdf", bbox_inches="tight")
    plt.close(fig)
    return out


# ── 1×3 summary figure ───────────────────────────────────────────────────────

def _draw_scatter_fit(ax, rows, setting, metric, x_max, r_min_global, r_ceil):
    """Scatter + power-law fit for one setting on ax."""
    color  = SETTING_COLORS[setting]
    marker = SETTING_MARKERS[setting]
    slabel = SETTING_LABELS[setting]

    pts = points_for(rows, setting, metric, r_max=x_max)
    if not pts:
        return
    fit = fit_power(pts)
    if all(math.isfinite(fit[k]) for k in ("c", "p", "r2")):
        leg_label = f"{slabel}  $p$={fit['p']:.3f}, $R^2$={fit['r2']:.3f}"
    else:
        leg_label = slabel

    ax.scatter([r for r, _ in pts], [y for _, y in pts],
               color=color, marker=marker, s=28,
               zorder=4, linewidths=0.4, edgecolors="white", label=leg_label)
    r_curve, y_curve = _fit_curve(fit, r_min_global, r_ceil)
    if r_curve:
        ax.plot(r_curve, y_curve, color=color, linestyle="--",
                linewidth=1.7, zorder=3, alpha=0.82)


def _draw_scatter_fit_piecewise(ax, rows, setting, metric, x_max,
                                r_min_global, r_ceil, r_break: float,
                                setting_idx: int = 0,
                                color: Optional[str] = None,
                                label: Optional[str] = None,
                                show_ann: bool = True,
                                linestyle_lo: str = "-",
                                linestyle_hi: str = "--"):
    """Scatter + two piecewise free power-law fits separated at r_break.

    Segment 1 [r_min, r_break]: linestyle_lo fit line, annotated with p₁.
    Segment 2 [r_break, r_ceil]: linestyle_hi fit line, annotated with p₂.

    setting_idx (0 or 1) staggers the annotation x-position so labels
    from two settings do not overlap in the high-r segment.
    Optional color/label override SETTING_COLORS/SETTING_LABELS.
    show_ann=False suppresses p-exponent annotations (useful when many curves share a panel).
    """
    color  = color  or SETTING_COLORS[setting]
    marker = SETTING_MARKERS[setting]
    slabel = label  or SETTING_LABELS[setting]

    pts_all  = points_for(rows, setting, metric, r_max=x_max)
    pts_low  = [(r, y) for r, y in pts_all if r <= r_break]
    pts_high = [(r, y) for r, y in pts_all if r >  r_break]
    if not pts_all:
        return

    ax.scatter([r for r, _ in pts_all], [y for _, y in pts_all],
               color=color, marker=marker, s=28, zorder=4,
               linewidths=0.4, edgecolors="white", label=slabel)

    def _annotate_fit(pts_seg, r_lo, r_hi, linestyle, ann_x_frac):
        if len(pts_seg) < 2:
            return
        fit = fit_power(pts_seg)
        if not all(math.isfinite(fit[k]) for k in ("c", "p", "r2")):
            return
        rc, yc = _fit_curve(fit, r_lo, r_hi)
        if not rc:
            return
        ax.plot(rc, yc, color=color, linestyle=linestyle,
                linewidth=1.8, zorder=3, alpha=0.88)
        if show_ann:
            r_ann = r_lo + (r_hi - r_lo) * ann_x_frac
            y_ann = fit["c"] * r_ann ** fit["p"]
            ax.annotate(
                f"$p$={fit['p']:.2f}",
                xy=(r_ann, y_ann),
                xytext=(0, 9), textcoords="offset points",
                fontsize=8, color=color, ha="center", va="bottom",
            )

    # low segment — SGD at 35%, GAM at 65% of [r_lo1, r_break]
    low_fracs  = [0.35, 0.65]
    # high segment — SGD at 30%, GAM at 65% of [r_break, r_ceil]
    high_fracs = [0.30, 0.65]

    _annotate_fit(pts_low,  r_min_global, r_break, linestyle_lo, low_fracs[setting_idx])
    _annotate_fit(pts_high, r_break,      r_ceil,  linestyle_hi, high_fracs[setting_idx])

    ax.axvline(r_break, color="grey", linestyle=":", linewidth=0.9,
               alpha=0.5, zorder=2)


def _style_ax(ax, xlabel, ylabel, title, r_ceil):
    ax.set_xlim(0.0, r_ceil * 1.06)
    ax.set_ylim(bottom=0)
    ax.set_xlabel(xlabel, fontsize=12)
    ax.set_ylabel(ylabel, fontsize=12)
    ax.set_title(title, fontsize=12, fontweight="bold", pad=5)
    fmt = ScalarFormatter(useMathText=True)
    fmt.set_scientific(True)
    fmt.set_powerlimits((-3, 3))
    ax.yaxis.set_major_formatter(fmt)
    ax.yaxis.get_offset_text().set_fontsize(10)
    ax.tick_params(axis="y", labelsize=11)
    ax.tick_params(axis="x", labelsize=10)
    ax.legend(loc="upper left", fontsize=9, framealpha=0.88,
               handletextpad=0.4, borderpad=0.5, labelspacing=0.35)
    ax.grid(True, alpha=0.22, linewidth=0.5)
    ax.spines["top"].set_visible(False)
    ax.spines["right"].set_visible(False)


def draw_1x3_pdf(
    result_dir: Path,
    rows: List[Dict[str, str]],
    x_max: Optional[float] = 20.0,
    out_name: str = "fqa_1x3.pdf",
) -> Path:
    """1×3 figure:
      (a) True old-task loss movement  (loss_delta_abs)
      (b) Raw surrogate error          (endpoint_error)
      (c) Linear term vs Fisher quad   (crossover, same axis)
    """
    all_r = sorted({_float(r["radius"]) for r in rows if _float(r["radius"]) > 0})
    r_min_global = min(all_r) if all_r else 0.5
    r_ceil = x_max if x_max is not None else (max(all_r) if all_r else 50.0)

    fig, (ax_a, ax_b, ax_c) = plt.subplots(1, 3, figsize=(13, 4.2))
    fig.suptitle(
        "FQA diagnostics: Taylor decomposition of old-task loss movement",
        fontsize=12, fontweight="bold",
    )

    # ── panel (a): true loss movement ────────────────────────────────────────
    for setting in SETTINGS:
        _draw_scatter_fit(ax_a, rows, setting, "loss_delta_abs",
                          x_max, r_min_global, r_ceil)
    _style_ax(ax_a, "radius $r$",
              r"$\mathbb{E}_u|\Delta L_A(r,u)|$",
              r"(a) True old-task loss movement", r_ceil)

    # ── panel (b): raw surrogate error ───────────────────────────────────────
    for setting in SETTINGS:
        _draw_scatter_fit(ax_b, rows, setting, "endpoint_error",
                          x_max, r_min_global, r_ceil)
    _style_ax(ax_b, "radius $r$",
              r"$\mathbb{E}_u|\Delta L_A - Q_F|$",
              r"(b) Raw surrogate error", r_ceil)

    # ── panel (c): linear vs quadratic, scatter + fit, crossover annotated ──────
    for setting in SETTINGS:
        color  = SETTING_COLORS[setting]
        marker = SETTING_MARKERS[setting]
        slabel = SETTING_LABELS[setting]

        pts_lin  = points_for(rows, setting, "linear_term_abs",      r_max=x_max)
        pts_quad = points_for(rows, setting, "endpoint_fisher_quad",  r_max=x_max)

        # scatter + power-law fit for linear term (solid)
        if pts_lin:
            ax_c.scatter([r for r, _ in pts_lin], [y for _, y in pts_lin],
                         color=color, marker=marker, s=22, zorder=4,
                         linewidths=0.4, edgecolors="white",
                         label=f"{slabel}  linear $|g_A^\\top(ru)|$")
            fit_lin = fit_power(pts_lin)
            rc, yc = _fit_curve(fit_lin, r_min_global, r_ceil)
            if rc:
                ax_c.plot(rc, yc, color=color, linestyle="-", linewidth=1.7,
                          zorder=3, alpha=0.85)

        # scatter + power-law fit for Fisher quad (dashed, lighter)
        if pts_quad:
            ax_c.scatter([r for r, _ in pts_quad], [y for _, y in pts_quad],
                         color=color, marker=marker, s=22, zorder=4,
                         linewidths=0.4, edgecolors="white", alpha=0.35)
            fit_quad = fit_power(pts_quad)
            rc, yc = _fit_curve(fit_quad, r_min_global, r_ceil)
            if rc:
                ax_c.plot(rc, yc, color=color, linestyle="--", linewidth=1.7,
                          zorder=3, alpha=0.55,
                          label=f"{slabel}  Fisher $Q_F$")

        # crossover annotation
        r_star = _find_crossover(rows, setting, "linear_term_abs", "endpoint_fisher_quad")
        short  = "GAM" if "gam" in setting else "SGD"
        if r_star is not None and r_star <= r_ceil:
            ax_c.axvline(r_star, color=color, linestyle=":", linewidth=1.3,
                         alpha=0.85, zorder=3)
            ax_c.text(r_star + r_ceil * 0.012, 0.96,
                      f"$r^*_{{\\rm {short}}}={r_star:.1f}$",
                      transform=ax_c.get_xaxis_transform(),
                      fontsize=9, color=color, va="top", ha="left")
        elif r_star is not None:
            # r* outside visible range: annotate at right edge
            ax_c.text(0.98, 0.97 - (0.12 * list(SETTINGS).index(setting)),
                      f"$r^*_{{\\rm {short}}}={r_star:.1f}$ $\\rightarrow$",
                      transform=ax_c.transAxes,
                      fontsize=9, color=color, va="top", ha="right")

    _style_ax(ax_c, "radius $r$", "magnitude",
              r"(c) Linear vs Fisher quadratic  ($r^*$: crossover)", r_ceil)
    ax_c.legend(loc="upper left", fontsize=8.5, framealpha=0.88, ncol=2,
                handletextpad=0.4, borderpad=0.5, labelspacing=0.3)

    plt.tight_layout()
    out = result_dir / out_name
    fig.savefig(str(out), format="pdf", bbox_inches="tight")
    plt.close(fig)
    return out


def draw_1x3_simple_piecewise_pdf(
    result_dir: Path,
    rows: List[Dict[str, str]],
    x_max: float = 10.0,
    r_break: float = 5.0,
    out_name: str = "fqa_1x3_simple_piecewise.pdf",
) -> Path:
    """1×3 piecewise figure (endpoint / diagonal Fisher only):
      (a) True old-task loss movement
      (b) Surrogate error |ΔL − Q_F^diag|
      (c) First-order stationarity term |g_A^⊤(ru)|

    Each panel: piecewise free power-law fit split at r_break.
    x_max and x-tick spacing of 1 for easy reading.
    """
    all_r = sorted({_float(r["radius"]) for r in rows if _float(r["radius"]) > 0})
    r_min_global = min(all_r) if all_r else 0.5
    r_ceil = x_max

    PANELS = [
        ("loss_delta_abs",
         r"$\overline{\Delta L}_A(r)$",
         r"(a) True old-task loss movement"),
        ("endpoint_error",
         r"$\overline{\mathcal{E}}_A(r)$",
         r"(b) Surrogate error  $|\Delta L_A - Q_F^{\rm diag}|$"),
        ("linear_term_abs",
         r"$\overline{G}_A^{\rm abs}(r)$",
         r"(c) First-order stationarity  $\overline{G}_A^{\rm abs}$"),
    ]

    fig, axes = plt.subplots(1, 3, figsize=(13, 4.5))
    fig.suptitle(
        f"FQA diagnostics (diagonal Fisher, $r \\in [0,{int(x_max)}]$,"
        f" piecewise split $r={r_break}$)",
        fontsize=11, fontweight="bold",
    )

    for ax, (metric, ylabel, title) in zip(axes, PANELS):
        for idx, setting in enumerate(SETTINGS):
            _draw_scatter_fit_piecewise(ax, rows, setting, metric,
                                        x_max, r_min_global, r_ceil, r_break,
                                        setting_idx=idx)
        _style_ax(ax, "radius $r$", ylabel, title, r_ceil)
        ax.xaxis.set_major_locator(MultipleLocator(1))
        r_mid_lo = r_break * 0.5
        r_mid_hi = r_break + (r_ceil - r_break) * 0.5
        ax.text(r_mid_lo, 0.015, f"$r<{r_break}$",
                transform=ax.get_xaxis_transform(),
                fontsize=8, color="grey", ha="center", va="bottom")
        ax.text(r_mid_hi, 0.015, f"$r>{r_break}$",
                transform=ax.get_xaxis_transform(),
                fontsize=8, color="grey", ha="center", va="bottom")

    plt.tight_layout()
    out = result_dir / out_name
    fig.savefig(str(out), format="pdf", bbox_inches="tight")
    plt.close(fig)
    return out


