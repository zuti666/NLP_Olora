"""
2×2 linear-scale FQA diagnostics figure, output as PDF.
Legend placed inside each panel.  Font: Times New Roman.

Four panels:
  (a) E|Delta L_A|       — true old-task loss movement
  (b) E[Q_F]             — Fisher quadratic surrogate (endpoint)
  (c) E|Delta L_A - Q_F| — raw surrogate error (endpoint)
  (d) E|g_A^T Delta|     — first-order stationarity term

Each panel shows SGD and GAM data points + power-law fit (y = c * r^p).
Input: fqa_partial_means.csv (generated by summarize_fqa_validity.convert_fqa_partial_dir).
Only rows with main_prefix == "endpoint" are used.

Usage:
  conda run -n low-rank-cl python utils/plot_fqa_linear_pdf.py <partial_dir>

Outputs (both written, neither overwrites the other):
  <partial_dir>/fqa_linear_2x2.pdf          full range r ∈ [0, 50]
  <partial_dir>/fqa_linear_2x2_r0to5.pdf    zoomed range r ∈ [0, 5]
"""

