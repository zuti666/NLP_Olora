# ── crossover figure ─────────────────────────────────────────────────────────

def _find_crossover(rows: List[Dict[str, str]], setting: str,
                    col_lin: str, col_quad: str) -> Optional[float]:
    """Return radius where col_lin ≈ col_quad (linear interpolation)."""
    pts = sorted(
        ((_float(r["radius"]), _float(r[col_lin]), _float(r[col_quad]))
         for r in rows
         if r.get("setting") == setting and _float(r["radius"]) > 0
         and math.isfinite(_float(r[col_lin])) and math.isfinite(_float(r[col_quad]))),
        key=lambda t: t[0],
    )
    for (r0, l0, q0), (r1, l1, q1) in zip(pts, pts[1:]):
        d0, d1 = l0 - q0, l1 - q1
        if d0 * d1 <= 0 and abs(d1 - d0) > 1e-30:
            return r0 + (r1 - r0) * (-d0) / (d1 - d0)
    return None


def draw_crossover_pdf(
    result_dir: Path,
    rows: List[Dict[str, str]],
    x_max: Optional[float] = None,
    out_name: str = "fqa_crossover.pdf",
) -> Path:
    """Single-panel figure: linear term vs Fisher quadratic for each setting.

    Both metrics are plotted on the same axes with crossover points annotated.
    Shaded regions mark where linear dominates (left) vs quadratic dominates (right).
    """
    col_lin  = "linear_term_abs"
    col_quad = "endpoint_fisher_quad"

    all_r = sorted({_float(r["radius"]) for r in rows if _float(r["radius"]) > 0})
    r_ceil = x_max if x_max is not None else (max(all_r) if all_r else 50.0)

    fig, ax = plt.subplots(figsize=(7, 4.5))

    crossovers: List[Tuple[str, float]] = []

    for setting in SETTINGS:
        color  = SETTING_COLORS[setting]
        slabel = SETTING_LABELS[setting]

        pts_lin  = points_for(rows, setting, col_lin,  r_max=x_max)
        pts_quad = points_for(rows, setting, col_quad, r_max=x_max)

        if pts_lin:
            ax.plot([r for r, _ in pts_lin],  [y for _, y in pts_lin],
                    color=color, linestyle="-",  linewidth=1.8,
                    label=f"{slabel}  linear $|g_A^\\top(ru)|$", zorder=4)
        if pts_quad:
            ax.plot([r for r, _ in pts_quad], [y for _, y in pts_quad],
                    color=color, linestyle="--", linewidth=1.8,
                    label=f"{slabel}  Fisher $Q_F$", zorder=4)

        r_star = _find_crossover(rows, setting, col_lin, col_quad)
        if r_star is not None and r_star <= r_ceil:
            crossovers.append((setting, r_star))

    # shade and annotate crossover regions
    colors_shade = {s: SETTING_COLORS[s] for s in SETTINGS}
    for setting, r_star in crossovers:
        color = colors_shade[setting]
        ax.axvline(r_star, color=color, linestyle=":", linewidth=1.4, alpha=0.8, zorder=3)
        ax.text(
            r_star + r_ceil * 0.01, 0.97,
            f"$r^*={r_star:.1f}$",
            transform=ax.get_xaxis_transform(),
            fontsize=9, color=color, va="top", ha="left",
        )

    ax.set_xlim(0.0, r_ceil * 1.06)
    ax.set_ylim(bottom=0)
    ax.set_xlabel("radius $r$", fontsize=12)
    ax.set_ylabel("magnitude", fontsize=12)
    ax.set_title(
        "Linear term vs Fisher quadratic surrogate\n"
        r"(crossover $r^*$: linear $=$ quadratic)",
        fontsize=12, fontweight="bold",
    )

    fmt = ScalarFormatter(useMathText=True)
    fmt.set_scientific(True)
    fmt.set_powerlimits((-3, 3))
    ax.yaxis.set_major_formatter(fmt)
    ax.yaxis.get_offset_text().set_fontsize(10)
    ax.tick_params(labelsize=10)
    ax.legend(fontsize=8.5, framealpha=0.88, ncol=2,
              handletextpad=0.4, borderpad=0.5, labelspacing=0.3)
    ax.grid(True, alpha=0.22, linewidth=0.5)
    ax.spines["top"].set_visible(False)
    ax.spines["right"].set_visible(False)

    plt.tight_layout()
    out = result_dir / out_name
    fig.savefig(str(out), format="pdf", bbox_inches="tight")
    plt.close(fig)
    return out


